import {readFile, writeFile, readdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import path from 'node:path';

const root=fileURLToPath(new URL('../',import.meta.url));
const release=JSON.parse(await readFile(root+'browser-workspace/release.json','utf8'));
const localAssets={},upstreamAssets={},checksums={};
const clientRevision=process.env.DOXA_CLIENT_REVISION||process.env.GITHUB_SHA;
if(!/^[a-f0-9]{40}$/.test(clientRevision))throw Error('Pin the compiled browser source revision');
const types={'.html':'text/html; charset=utf-8','.js':'text/javascript; charset=utf-8','.mjs':'text/javascript; charset=utf-8','.css':'text/css; charset=utf-8','.json':'application/json','.svg':'image/svg+xml','.webp':'image/webp'};
async function walk(dir){
  for(const file of (await readdir(dir,{withFileTypes:true})).sort((a,b)=>a.name.localeCompare(b.name))){
    const name=path.join(dir,file.name);
    if(file.isDirectory()){await walk(name);continue;}
    // The runtime loads the pinned /verifier/ WASM. Vite's unused fallback
    // must not inflate the Worker by another 12 MB.
    if(file.name.endsWith('.wasm'))continue;
    const key='/'+path.relative(root+'browser-workspace/web/dist',name);
    const bytes=await readFile(name);
    if(!(await readFile(root+'browser-workspace/client'+key)).equals(bytes))throw Error('Committed client differs from build: '+key);
    if (['.html','.css','.svg','.json'].includes(path.extname(name))) localAssets[key]={type:types[path.extname(name)]||'application/octet-stream',data:bytes.toString('base64')};
    else upstreamAssets[key]=`https://raw.githubusercontent.com/sargonxg/DOXA-by-TACITUS/${clientRevision}/browser-workspace/client${key}`;
    checksums[key]=createHash('sha256').update(bytes).digest('hex');
  }
}
await walk(root+'browser-workspace/web/dist');
if(!localAssets['/index.html'])throw Error('Build the browser client first');
const html=Buffer.from(localAssets['/index.html'].data,'base64').toString('utf8');
if(!html.includes('Audit political bias in documents.'))throw Error('Unexpected product entry');
for(const file of release.runtime_files){
  if(!/^dist\/[a-zA-Z0-9._/-]+$/.test(file)||file.includes('..'))throw Error('Unexpected pinned asset');
  const key='/'+file.slice(5);
  if(!localAssets[key])upstreamAssets[key]=`https://huggingface.co/spaces/Giuliocc/doxa-lab/resolve/${release.source_revision}/${file}`;
}
for(const file of release.scorecard_files){
  if(!/^dist\/[a-zA-Z0-9._/-]+$/.test(file)||file.includes('..'))throw Error('Unexpected scorecard asset');
  upstreamAssets['/scorecard/'+file.slice(5)]=`https://huggingface.co/spaces/Giuliocc/doxa-scorecard/resolve/${release.scorecard_revision}/${file}`;
}
await writeFile(root+'infra/cloudflare/src/browser-assets.mjs','// Generated by scripts/build-browser-workspace.mjs\nexport const release='+JSON.stringify({source_revision:release.source_revision,client_revision:clientRevision})+';\nexport const localAssets='+JSON.stringify(localAssets)+';\nexport const upstreamAssets='+JSON.stringify(upstreamAssets)+';\n');
await writeFile(root+'browser-workspace/build-receipt.json',JSON.stringify({schema:'tacitus.doxa-browser-build/1',source_revision:release.source_revision,assets:checksums,upstream_paths:Object.keys(upstreamAssets).sort()},null,2)+'\n');
console.log(`Prepared ${Object.keys(localAssets).length} client assets and ${Object.keys(upstreamAssets).length} pinned upstream assets. No model calls.`);
