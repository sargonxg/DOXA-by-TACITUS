def _text(value: Any, field: str, maximum: int, *, default: str = "", required: bool = False) -> str:
    if value is None:
        value = default
    if not isinstance(value, str):
        raise ValueError(f"{field} must be text")
    value = value.strip()
    if len(value) > maximum or (required and not value):
        raise ValueError(f"{field} must contain {'1 to ' if required else 'at most '}{maximum} characters")
    return value


def _object(value: Any, field: str, allowed: set[str]) -> dict:
    if not isinstance(value, dict):
        raise ValueError(f"{field} must be an object")
    if any(not isinstance(key, str) for key in value):
        raise ValueError(f"{field} field names must be text")
    if set(value) - allowed:
        raise ValueError(f"Unknown {field} field: {sorted(set(value) - allowed)[0]}")
    return value


def _policy(value: Any) -> dict | None:
    if value is None:
        return None
    value = _object(value, "company_policy", {"title", "version", "text"})
    return {"title": _text(value.get("title"), "company_policy.title", 200, required=True),
            "version": _text(value.get("version"), "company_policy.version", 100, required=True),
            "text": _text(value.get("text"), "company_policy.text", 20000, required=True)}


def _comparator(value: Any) -> dict | None:
    if value is None:
        return None
    value = _object(value, "comparator", {"question", "inclusion_rules", "topic", "genres", "date_start", "date_end", "source_groups"})
    result = {"question": _text(value.get("question"), "comparator.question", 4000, required=True),
              "inclusion_rules": _text(value.get("inclusion_rules"), "comparator.inclusion_rules", 4000, required=True),
              "topic": _text(value.get("topic"), "comparator.topic", 1000)}
    genres = value.get("genres", [])
    if not isinstance(genres, list) or len(genres) > 20:
        raise ValueError("comparator.genres must be a list of at most 20 genres")
    result["genres"] = list(dict.fromkeys(_text(item, "genre", 100, required=True) for item in genres))
    for name in ("date_start", "date_end"):
        item = _text(value.get(name), f"comparator.{name}", 10)
        if item:
            try:
                date.fromisoformat(item)
            except ValueError:
                raise ValueError(f"comparator.{name} must be an ISO calendar date") from None
            if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", item):
                raise ValueError(f"comparator.{name} must use YYYY-MM-DD")
        result[name] = item
    if result["date_start"] and result["date_end"] and result["date_start"] > result["date_end"]:
        raise ValueError("Comparator start date must not follow its end date")
    groups = value.get("source_groups", [])
    if not isinstance(groups, list) or len(groups) > 20:
        raise ValueError("comparator.source_groups must contain at most 20 groups")
    result["source_groups"] = []
    seen: set[str] = set()
    for group in groups:
        group = _object(group, "source group", {"label", "document_ids"})
        label = _text(group.get("label"), "source group label", 200, required=True)
        if label in seen:
            raise ValueError("Comparator source group labels must be unique")
        seen.add(label)
        ids = group.get("document_ids", [])
        if not isinstance(ids, list) or len(ids) > 10000:
            raise ValueError("Source group document_ids must be a list of at most 10000 IDs")
        result["source_groups"].append({"label": label, "document_ids": list(dict.fromkeys(_text(item, "document_id", 200, required=True) for item in ids))})
    return result


def validate_brief(payload: dict) -> dict:
    """Normalize customer intent; do not accept client claims of validation/review.

    Revalidate a stored normalized brief by passing only its user-authored fields;
    machine readiness/provenance must come from this registry on creation.
    """
    payload = _object(payload, "brief", {"profile_id", "question", "audience", "perspective", "lens_ids", "company_policy", "comparator"})
    profile = get_profile(payload.get("profile_id"))
    lenses = payload.get("lens_ids", profile["default_lens_ids"])
    if not isinstance(lenses, list) or not 1 <= len(lenses) <= 8:
        raise ValueError("lens_ids must contain between 1 and 8 declared lenses")
    lens_ids = []
    for lens_id in lenses:
        if not isinstance(lens_id, str):
            raise ValueError("Each lens ID must be text")
        lens = get_lens(lens_id)
        if lens["id"] not in lens_ids:
            lens_ids.append(lens["id"])
    policy = _policy(payload.get("company_policy"))
    if policy and profile["id"] != "company":
        raise ValueError("company_policy belongs to the company service profile")
    comparator = _comparator(payload.get("comparator"))
    result = {"schema_version": BRIEF_VERSION, "method_version": PROFILE_VERSION,
              "profile_id": profile["id"],
              "question": _text(payload.get("question"), "question", 4000, default=profile["default_question"], required=True),
              "audience": _text(payload.get("audience"), "audience", 2000, default=profile["default_audience"], required=True),
              "perspective": _text(payload.get("perspective"), "perspective", 2000, default=profile["default_persona"], required=True),
              "lens_ids": lens_ids, "company_policy": policy, "comparator": comparator,
              "comparator_status": "declared_unverified" if comparator else "not_declared",
              "policy_alignment_status": "policy_supplied_unverified" if policy else "not_requested",
              "readiness": deepcopy(_READINESS), "report_sections": profile["report_sections"]}
    result["fingerprint"] = _digest(result)
    return result


def _digest(value: Any) -> str:
    return hashlib.sha256(json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"), allow_nan=False).encode()).hexdigest()


# These patterns intentionally describe forms. They do not assign a tone score.
_RULES = (
    ("request_marker", "Request wording", "request", r"\b(?:please|could you|would you|can you|would it be possible to|may I ask you to)\b"),
    ("future_commitment_marker", "Future commitment wording", "commitment", r"\b(?:I|we)\s+(?:will|shall|promise to|commit to)\s+(?!(?:not|never)\b)[A-Za-z]+\b"),
    ("time_constraint_marker", "Time or deadline wording", "time_constraint", r"\b(?:by|before|no later than)\s+(?:(?:Monday|Tuesday|Wednesday|Thursday|Friday|Saturday|Sunday|tomorrow|tonight|noon|midnight)\b|\d{4}-\d{2}-\d{2}\b|\d{1,2}(?::\d{2})?\s*(?:am|pm)\b|the\s+end\s+of\s+(?:the\s+)?(?:day|week|month)\b)"),
    ("hedge_marker", "Qualification wording", None, r"\b(?:perhaps|possibly|maybe|might|seems?|appears?|in my view|I think|I suggest)\b"),
    ("imperative_form", "Sentence-initial imperative form", "request", r"(?:^|(?<=[.!?\n]))[ \t]*(?P<marker>(?:send|provide|review|confirm|complete|submit|respond|reply|check|update|return|schedule|share)\b)"),
)
_COMPILED_RULES = [(kind, label, act, re.compile(pattern, re.IGNORECASE)) for kind, label, act, pattern in _RULES]
_NON_AUTHOR_ROLES = {"quoted", "forwarded", "signature", "header"}
_OBSERVATION_LIMITATIONS = [
    "Rule matches establish observable wording only; they do not establish bias, politeness, intent or emotion.",
    "These English rules are incomplete and have not been independently validated for detection recall or precision.",
    "Inline reported speech, negation, irony and missing context may change a reading; speaker attribution is not assessed.",
    "No match is not a negative judgment, and marker frequency is not a communication-quality score.",
    "Mail roles use parser heuristics and unverified headers; eligibility does not prove authorship or endorsement.",
]


def observe_communication(blocks: list[dict], profile_id: str = "personal", *, max_observations: int = 5000) -> dict:
    """Inspect all supplied blocks without inventing a recipient reaction.

    Mail parser role markers exclude quoted/history/signature material from
    authored-unit counts, while retaining visible observations for context.
    """
    get_profile(profile_id)
    if not isinstance(blocks, list) or len(blocks) > 100000:
        raise ValueError("blocks must be a list of at most 100000 source blocks")
    if type(max_observations) is not int or not 1 <= max_observations <= 20000:
        raise ValueError("max_observations must be between 1 and 20000")
    seen = set()
    observations = []
    counts: dict[str, int] = {item[0]: 0 for item in _RULES}
    excluded = eligible_blocks = characters = matched = 0
    for block in blocks:
        if not isinstance(block, dict) or not isinstance(block.get("id"), str) or not block["id"] or not isinstance(block.get("text"), str):
            raise ValueError("Each source block needs a stable text ID and unmodified text")
        identity = (block.get("document_id", ""), block["id"])
        if identity in seen:
            raise ValueError("Source block IDs must be unique within a document")
        seen.add(identity)
        text = block["text"]
        characters += len(text)
        role = block.get("mail_role")
        eligible = (role in {None, "authored"} and not block.get("ineligible_for_author_counts", False)
                    and block.get("eligible_for_author_counts", True) is True)
        if eligible:
            eligible_blocks += 1
        else:
            excluded += 1
        for kind, label, act, pattern in _COMPILED_RULES:
            for match in pattern.finditer(text):
                start, end = match.span("marker") if "marker" in match.re.groupindex else match.span()
                matched += 1
                if eligible:
                    counts[kind] += 1
                if len(observations) >= max_observations:
                    continue
                quote = text[start:end]
                source = {"block_id": block["id"], "start": start, "end": end, "quote": quote}
                if block.get("document_id") is not None:
                    source["document_id"] = block["document_id"]
                observations.append({"id": _digest([OBSERVATION_VERSION, identity, kind, start, end])[:24],
                                     **source, "kind": kind, "label": label,
                                     "communicative_act_candidate": act, "attribution": "not_assessed",
                                     "count_eligible": eligible, "mail_role": role,
                                     "status": "observed_wording", "review_status": "unreviewed",
                                     "offset_unit": "unicode_code_points",
                                     "provenance": {"origin": "deterministic_rule", "method_version": OBSERVATION_VERSION,
                                                    "rule_id": kind, "model_inference": False}})
    observations.sort(key=lambda item: (str(item.get("document_id", "")), item["block_id"], item["start"], item["kind"]))
    return {"schema_version": OBSERVATION_VERSION, "profile_id": profile_id, "observations": observations,
            "counts": counts, "coverage": {"blocks_scanned": len(blocks), "characters_scanned": characters,
                                            "authored_eligible_blocks": eligible_blocks, "excluded_context_blocks": excluded,
                                            "rule_matches": matched, "observations_returned": len(observations),
                                            "observations_omitted": matched - len(observations),
                                            "source_scan_complete": True, "observations_complete": matched == len(observations)},
            "readiness": deepcopy(_READINESS), "limitations": list(_OBSERVATION_LIMITATIONS)}


def _number(value: Any, field: str) -> float:
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise ValueError(f"{field} must be a finite nonnegative number")
    try:
        number = float(value)
    except (ValueError, OverflowError):
        raise ValueError(f"{field} must be a finite nonnegative number") from None
    if not math.isfinite(number) or not 0 <= number <= 1000000:
        raise ValueError(f"{field} must be a finite number from zero to 1000000")
    return number


def _normalized_existing_brief(brief: Any) -> dict:
    if not isinstance(brief, dict):
        raise ValueError("brief must be an object")
    if brief.get("schema_version", BRIEF_VERSION) != BRIEF_VERSION or brief.get("method_version", PROFILE_VERSION) != PROFILE_VERSION:
        raise ValueError("Unsupported service brief version; create an explicit new brief")
    normalized = validate_brief({key: brief[key] for key in ("profile_id", "question", "audience", "perspective", "lens_ids", "company_policy", "comparator") if key in brief})
    if "fingerprint" in brief and brief["fingerprint"] != normalized["fingerprint"]:
        raise ValueError("Service brief fingerprint no longer matches its analytical fields")
    return normalized


def estimate_analysis(documents: list[dict], brief: dict, *, prices: dict | None = None,
                      max_unit_chars: int = 1200, context_sentences: int = 2) -> dict:
    """Count actual source units where available; model token/cost assumptions.

    Token ranges are English-oriented heuristics, not confidence intervals or a
    tokenizer measurement. Costs exclude retries and non-inference delivery work.
    """
    if not isinstance(documents, list) or len(documents) > 100000:
        raise ValueError("documents must be a list of at most 100000 source records")
    # Stored briefs include machine metadata. Rebuild from trusted registry and
    # user fields instead of trusting a supplied readiness flag or fingerprint.
    normalized = _normalized_existing_brief(brief)
    if type(max_unit_chars) is not int or not 200 <= max_unit_chars <= 4000 or type(context_sentences) is not int or not 0 <= context_sentences <= 4:
        raise ValueError("Unit size must be 200–4000 characters and context 0–4 sentences")
    criteria = sum(len(get_lens(lens_id)["criteria"]) for lens_id in normalized["lens_ids"])
    words = characters = blocks_count = actual_units = approximate_units = 0
    input_source_chars = 0
    metadata_only = 0
    seen = set()
    for index, document in enumerate(documents):
        if not isinstance(document, dict):
            raise ValueError("Each document must be an object")
        document_id = document.get("id")
        if document_id is not None:
            if not isinstance(document_id, str) or not document_id:
                raise ValueError("Document IDs must be nonempty text")
            if document_id in seen:
                raise ValueError("Source selection must not contain duplicate documents")
            seen.add(document_id)
        blocks = document.get("blocks")
        if blocks is None:
            count = document.get("word_count", 0)
            if type(count) is not int or not 0 <= count <= 1000000000:
                raise ValueError("word_count must be an integer from zero to 1000000000")
            metadata_only += 1
            words += count
            estimated_chars = count * 6
            approximate_units += math.ceil(estimated_chars / max_unit_chars)
            input_source_chars += estimated_chars * (1 + context_sentences / 4)
            continue
        if not isinstance(blocks, list):
            raise ValueError("Source blocks must be a list")
        source = {**document, "id": document_id or f"estimate-source-{index}", "blocks": blocks}
        units = build_units(source, max_unit_chars=max_unit_chars, context_sentences=context_sentences)
        actual_units += len(units)
        for block in blocks:
            words += len(block["text"].split())
            characters += len(block["text"])
        blocks_count += len(blocks)
        for unit in units:
            input_source_chars += len(unit["text"]) + sum(len(item["text"]) for item in unit["context_before"] + unit["context_after"])
    total_units = actual_units + approximate_units
    # Declared planning assumptions, not a reconstruction of provider requests.
    overhead_chars = len(json.dumps([get_lens(item) for item in normalized["lens_ids"]], ensure_ascii=False)) + 4000
    estimated_input_chars = input_source_chars + total_units * overhead_chars
    detail_passes = math.ceil(criteria / 2)
    input_low = math.ceil(estimated_input_chars / 5)
    input_high = math.ceil(estimated_input_chars * (1 + detail_passes) / 2)
    output_low = total_units * (32 + criteria * 4)
    output_high = total_units * (800 + detail_passes * 1600)
    cost = None
    if prices is not None:
        prices = _object(prices, "prices", {"input_usd_per_million", "output_usd_per_million"})
        if set(prices) != {"input_usd_per_million", "output_usd_per_million"}:
            raise ValueError("Both input and output USD rates must be supplied")
        input_rate = _number(prices["input_usd_per_million"], "input_usd_per_million")
        output_rate = _number(prices["output_usd_per_million"], "output_usd_per_million")
        cost = {"currency": "USD", "low": round((input_low * input_rate + output_low * output_rate) / 1000000, 8),
                "high": round((input_high * input_rate + output_high * output_rate) / 1000000, 8),
                "rates": {"input_usd_per_million": input_rate, "output_usd_per_million": output_rate},
                "kind": "modeled_inference_only", "customer_price": False, "vendor_invoice": False}
    return {"schema_version": ESTIMATE_VERSION, "profile_id": normalized["profile_id"],
            "brief_fingerprint": normalized["fingerprint"],
            "source": {"documents": len(documents), "words": words, "characters": characters if not metadata_only else None,
                       "known_characters": characters, "known_blocks": blocks_count, "metadata_only_documents": metadata_only},
            "work": {"actual_units": actual_units, "estimated_units": approximate_units, "total_planning_units": total_units,
                     "criterion_count": criteria, "criterion_decisions": total_units * criteria,
                     "unit_builder_version": UNIT_BUILDER_VERSION,
                     "unit_builder_config": {"max_unit_chars": max_unit_chars, "context_sentences": context_sentences}},
            "tokens": {"kind": "unmeasured_english_heuristic", "input_low": input_low, "input_high": input_high,
                       "output_low": output_low, "output_high": output_high, "tokenizer_measured": False},
            "modeled_cost": cost, "cost_status": "modeled" if cost else "rates_not_supplied",
            "assumptions": ["Actual source units use the current unit builder when source blocks are supplied.",
                            "Metadata-only documents assume six characters per word; their units are estimates.",
                            "Input tokens assume two to five characters per token, repeated rubric plus 4000 formatting characters per unit.",
                            "The low scenario models classification only; the high scenario adds one detail pass per two criteria for every unit.",
                            "The output high scenario allows 800 classification tokens and 1600 per detail pass; batching and actual requests are unmeasured.",
                            "These ranges are planning heuristics, not guaranteed bounds, measured provider requests or confidence intervals."],
            "excluded_costs": ["retries", "verification", "OCR", "storage", "compute lifecycle", "network", "exports", "expert review", "support", "payment fees"],
            "readiness": deepcopy(_READINESS)}


def report_brief(brief: dict) -> dict:
    """Task-specific report contract; never mark a generated report reviewed."""
