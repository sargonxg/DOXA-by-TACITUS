"""Bounded, offline document extraction with stable source blocks.

Stored block text is the extractor's exact output. Consumers must use these
strings, rather than a second normalized copy, when checking evidence offsets.
"""
from __future__ import annotations

import hashlib
import importlib.util
import os
from pathlib import Path
import re
from html.parser import HTMLParser
import zipfile
import xml.etree.ElementTree as ET

MAX_FILE_BYTES = 500 * 1024 * 1024
MAX_TEXT_CHARS = 40_000_000
MAX_PAGES = 10_000
MAX_ZIP_BYTES = 200 * 1024 * 1024
MAX_XML_BYTES = 24 * 1024 * 1024
_W = "{http://schemas.openxmlformats.org/wordprocessingml/2006/main}"


def _xml(data: bytes) -> ET.Element:
    if len(data) > MAX_XML_BYTES:
        raise ValueError("A document XML part exceeds the extraction limit.")
    # OOXML generated by current editors uses UTF-8. Reject UTF-16/32 XML
    # rather than let a NUL-interleaved declaration bypass the entity check.
    if b"\x00" in data:
        raise ValueError("Document XML must use UTF-8; export a new DOCX copy.")
    if b"<!DOCTYPE" in data.upper() or b"<!ENTITY" in data.upper():
        raise ValueError("Document XML containing entity declarations is unsupported.")
    return ET.fromstring(data)


class _VisibleHTML(HTMLParser):
    """Extract visible text without running code, loading URLs, or using a DOM."""
    boundaries = {"p", "div", "section", "article", "header", "footer", "main",
                  "aside", "h1", "h2", "h3", "h4", "h5", "h6", "li", "ul",
                  "ol", "blockquote", "pre", "tr", "td", "th", "figcaption"}
    excluded = {"script", "style", "iframe", "object", "embed", "noscript",
                "template", "svg", "head"}

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.parts: list[str] = []
        self.blocks: list[str] = []
        self.skip: list[str] = []
        self.hidden: list[str] = []
        self.total_chars = 0

    def flush(self):
        text = "".join(self.parts)
        self.parts.clear()
        if text.strip():
            self.blocks.append(text)

    def handle_starttag(self, tag, attrs):
        attributes = dict(attrs)
        if self.skip:
            if tag in self.excluded:
                self.skip.append(tag)
            return
        if tag in self.excluded:
            self.flush()
            if tag != "embed":
                self.skip.append(tag)
            return
        if self.hidden:
            if tag not in {"br", "img", "hr", "input", "meta", "link", "source", "wbr"}:
                self.hidden.append(tag)
            return
        style = (attributes.get("style") or "").replace(" ", "").lower()
        if "hidden" in attributes or attributes.get("aria-hidden") == "true" or "display:none" in style or "visibility:hidden" in style:
            if tag not in {"br", "img", "hr", "input", "meta", "link", "source", "wbr"}:
                self.hidden.append(tag)
            return
        if tag in self.boundaries:
            self.flush()
        elif tag == "br":
            self.parts.append("\n")

    def handle_endtag(self, tag):
        if self.skip:
            if tag == self.skip[-1]:
                self.skip.pop()
            return
        if self.hidden:
            if tag == self.hidden[-1]:
                self.hidden.pop()
            return
        if tag in self.boundaries:
            self.flush()

    def handle_data(self, data):
        if self.skip or self.hidden:
            return
        self.total_chars += len(data)
        if self.total_chars > MAX_TEXT_CHARS:
            raise ValueError("Document text exceeds the extraction limit; split the source document.")
        self.parts.append(data)


def _decode(data: bytes, warnings: list[str]) -> str:
    try:
        return data.decode("utf-8-sig")
    except UnicodeDecodeError:
        try:
            result = data.decode("cp1252")
        except UnicodeDecodeError as exc:
            raise ValueError("Text encoding is unsupported. Save the document as UTF-8.") from exc
        warnings.append("Source decoded as Windows-1252; verify punctuation in the source preview.")
        return result


def _docx(path: Path, warnings: list[str]) -> tuple[list[dict], dict]:
    try:
        with zipfile.ZipFile(path) as archive:
            infos = archive.infolist()
            if len(infos) > 5000 or sum(p.file_size for p in infos) > MAX_ZIP_BYTES:
                raise ValueError("DOCX expands beyond the extraction resource limit.")
            if any(p.flag_bits & 1 for p in infos):
                raise ValueError("Encrypted DOCX files are unsupported; export an unlocked copy.")
            if any(p.filename.lower().endswith("vbaproject.bin") for p in infos):
                raise ValueError("Macro-containing documents are unsupported; export a clean DOCX or PDF.")
            root = _xml(archive.read("word/document.xml"))
            body = root.find(f"{_W}body")
            if body is None:
                raise ValueError("DOCX contains no document body.")
            blocks = []
            for index, paragraph in enumerate(body.iter(f"{_W}p"), start=1):
                pieces = []
                for node in paragraph.iter():
                    if node.tag == f"{_W}t":
                        pieces.append(node.text or "")
                    elif node.tag == f"{_W}tab":
                        pieces.append("\t")
                    elif node.tag in {f"{_W}br", f"{_W}cr"}:
                        pieces.append("\n")
                text = "".join(pieces)
                if text.strip():
                    blocks.append({"text": text, "paragraph": index})
            metadata = {}
            if "docProps/core.xml" in archive.namelist():
                try:
                    core = _xml(archive.read("docProps/core.xml"))
                    for node in core:
                        key = node.tag.rsplit("}", 1)[-1]
                        if key in {"creator", "title", "created", "modified", "subject"} and node.text:
                            metadata["author" if key == "creator" else key] = node.text
                except (ET.ParseError, ValueError):
                    warnings.append("DOCX metadata could not be read; document text was extracted.")
            warnings.append("DOCX paragraph locations are authoritative; page pagination depends on the original editor.")
            return blocks, metadata
    except (zipfile.BadZipFile, KeyError, ET.ParseError, RuntimeError) as exc:
        raise ValueError("DOCX is damaged or is not a valid Word document.") from exc


def _pdf(path: Path, warnings: list[str]) -> tuple[list[dict], int, dict, str]:
    try:
        import fitz
    except ImportError as exc:
        raise ValueError("PDF support requires PyMuPDF. Install the project's PDF dependencies.") from exc
    blocks: list[dict] = []
    empty_pages = []
    total_chars = 0
    try:
        with fitz.open(path) as document:
            if document.needs_pass:
                raise ValueError("PDF is encrypted; upload an unlocked copy.")
            pages = document.page_count
            if pages > MAX_PAGES:
                raise ValueError(f"PDF exceeds the {MAX_PAGES:,}-page extraction limit; split it into volumes.")
            metadata = {k: v for k, v in (document.metadata or {}).items() if v}
            for page_number in range(pages):
                page = document.load_page(page_number)
                texts = [b[4] for b in page.get_text("blocks", sort=True) if len(b) > 6 and b[6] == 0 and b[4].strip()]
                if not texts:
                    empty_pages.append(page_number + 1)
                for paragraph, text in enumerate(texts, start=1):
                    total_chars += len(text)
                    if total_chars > MAX_TEXT_CHARS:
                        raise ValueError("PDF text exceeds the extraction limit; split it into volumes.")
                    blocks.append({"text": text, "page": page_number + 1, "paragraph": paragraph})
                del page
    except ValueError:
        raise
    except Exception as exc:
        raise ValueError("PDF is damaged or could not be opened safely.") from exc
    if empty_pages:
        # OCR is an explicit processing choice: importing Docling must never
        # cause a model download or a surprise network transfer during upload.
        if os.environ.get("DOXA_ENABLE_OCR", "").lower() in {"1", "true", "yes"}:
            if importlib.util.find_spec("docling") is None:
                warnings.append("OCR requested but Docling is not installed. Install the OCR extra and prefetch its models.")
            elif pages > 200:
                warnings.append("Automatic OCR is limited to 200 pages per file in this profile; split this PDF for OCR.")
            else:
                try:
                    from docling.document_converter import DocumentConverter, PdfFormatOption
                    from docling.datamodel.base_models import InputFormat
                    from docling.datamodel.pipeline_options import PdfPipelineOptions
                    artifacts = os.environ.get("DOXA_DOCLING_ARTIFACTS")
                    if not artifacts or not Path(artifacts).is_dir():
                        warnings.append("OCR requires DOXA_DOCLING_ARTIFACTS pointing to prefetched local models; no models were downloaded.")
                    else:
                        options = PdfPipelineOptions(do_ocr=True, enable_remote_services=False, artifacts_path=Path(artifacts))
                        converter = DocumentConverter(format_options={InputFormat.PDF: PdfFormatOption(pipeline_options=options)})
                        converted = converter.convert(path).document
                        recovered = []
                        for item, _level in converted.iterate_items():
                            text = getattr(item, "text", None)
                            provenance = getattr(item, "prov", None)
                            page = getattr(provenance[0], "page_no", None) if provenance else None
                            if text and text.strip() and page in empty_pages:
                                recovered.append({"text": text, "page": page})
                        if recovered:
                            blocks.extend(recovered)
                            blocks.sort(key=lambda b: b.get("page", 0))
                            empty_pages = [p for p in empty_pages if not any(b.get("page") == p for b in recovered)]
                            warnings.append("OCR text is machine-recognized. Verify evidence against the original page image.")
                except Exception:
                    warnings.append("Local OCR failed; selectable text was preserved. Check prefetched model versions and OCR dependencies.")
        if empty_pages:
            preview = ", ".join(map(str, empty_pages[:20]))
            suffix = f" and {len(empty_pages)-20} more" if len(empty_pages) > 20 else ""
            warnings.append(f"No selectable text on pages {preview}{suffix}. These pages require OCR or are blank and are excluded from text analysis.")
        metadata["pages_without_text"] = empty_pages
    return blocks, pages, metadata, "pymupdf+docling-ocr" if any("machine-recognized" in w for w in warnings) else "pymupdf"


def extract_document(path: Path, filename: str | None = None) -> dict:
    """Extract supported local files; never fetch URLs or execute document code."""
    path = Path(path)
    if not path.is_file():
        raise ValueError("Source document does not exist or is not a regular file.")
    size = path.stat().st_size
    if size == 0:
        raise ValueError("Document is empty.")
    if size > MAX_FILE_BYTES:
        raise ValueError(f"Document exceeds the {MAX_FILE_BYTES // 1024 // 1024} MB extraction limit.")
    name = Path(filename or path.name).name
    extension = Path(name).suffix.lower()
    warnings: list[str] = []
    metadata = {"filename": name, "file_size": size}
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    metadata["sha256"] = digest.hexdigest()
    # Text/HTML/DOCX have no stable pagination without a layout engine. Zero
    # means unavailable, rather than pretending every upload is one page.
    pages = 0
    if extension == ".pdf":
        blocks, pages, extra, extractor = _pdf(path, warnings)
        metadata.update(extra)
        metadata["page_count_basis"] = "PDF page tree"
    elif extension == ".docx":
        blocks, extra = _docx(path, warnings)
        metadata.update(extra)
        extractor = "docx-xml"
        metadata["page_count_basis"] = "Unavailable: DOCX pagination depends on editor layout"
    elif extension in {".txt", ".md", ".markdown", ".html", ".htm"}:
        text = _decode(path.read_bytes(), warnings)
        if len(text) > MAX_TEXT_CHARS:
            raise ValueError("Document text exceeds the extraction limit; split the source document.")
        if "\x00" in text:
            raise ValueError("Document appears to contain binary data; export it as UTF-8 text.")
        if extension in {".html", ".htm"}:
            parser = _VisibleHTML()
            parser.feed(text)
            parser.close()
            parser.flush()
            texts = parser.blocks
            extractor = "stdlib-html-visible-text"
            warnings.append("HTML scripts, styles, embedded objects and hidden text are excluded; no external resources were loaded.")
        else:
            texts = re.split(r"\r?\n[ \t]*\r?\n", text)
            extractor = "utf-text"
        blocks = [{"text": value, "paragraph": i} for i, value in enumerate(texts, 1) if value.strip()]
        metadata["page_count_basis"] = "Unavailable: source format is not paginated"
    else:
        raise ValueError("Unsupported document format. Use PDF, DOCX, TXT, Markdown or HTML.")
    if not blocks:
        detail = " A scanned PDF requires local OCR; install and configure the OCR extra." if extension == ".pdf" else ""
        raise ValueError("Document contains no extractable text." + detail)
    if sum(len(b["text"]) for b in blocks) > MAX_TEXT_CHARS:
        raise ValueError("Extracted text exceeds the resource limit; split the source document.")
    for index, block in enumerate(blocks, start=1):
        block["id"] = f"b{index:06d}"
    word_count = sum(len(re.findall(r"\b[\w'-]+\b", block["text"])) for block in blocks)
    return {"blocks": blocks, "page_count": pages, "word_count": word_count,
            "extractor": extractor, "extraction_warnings": warnings, "metadata": metadata}
